"""Single source of truth for user-facing messages in the requests app.

همه‌ی متن‌های کاربرنمای فرم درخواست — خطاهای میدان، خطاهای آپلود، پیام‌های
framework و همان متن‌هایی که اعلان‌ها (WizardToast) از روی صفحه می‌خوانند —
یک بار اینجا تعریف می‌شوند تا خلاصه‌ی خطاها، اعلان‌ها و پیام‌های framework
همه یک صدا باشند.

متن‌ها با gettext_lazy از همین رشته‌ها ساخته می‌شوند تا فایل ترجمه‌ی اپ
(locale/fa/LC_MESSAGES/django.po) دقیقاً همین‌ها را پوشش دهد؛ اگر ترجمه به
هر دلیلی بارگذاری نشود، خود رشته که فارسی است نمایش داده می‌شود و چیزی
خراب نمی‌شود.
"""
from django.utils.translation import gettext_lazy as _

# ---------------------------------------------------------------------------
# helpers — جان‌مایه‌ی ارقام فارسی برای پیام‌های عدددار
# ---------------------------------------------------------------------------
_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
# جداکننده‌ی هزارگان فارسی (U+066C) — کامای لاتین در متن فارسی غلط است.
_THOUSANDS = "٬"


def fa_digits(value) -> str:
    """Latin digits → Persian digits (همان قاعده‌ی فیلتر fa_digits)."""
    return str(value).translate(_FA_DIGITS)


def thousands(value) -> str:
    """۱۲۳۴۵۶۷۸ → ۱۲۳٬۴۵۶٬۷۸ با ارقام فارسی و جداکننده‌ی فارسی."""
    return f"{int(value):,}".replace(",", _THOUSANDS).translate(_FA_DIGITS)


def megabytes(max_bytes: int) -> str:
    """Bytes → «۸ مگابایت» با ارقام فارسی (همان فرمول views.py)."""
    return f"{thousands(max_bytes // (1024 * 1024))} مگابایت"


# ---------------------------------------------------------------------------
# قواعد مشترک کلاینت / سرور — قالب همین‌ها را در data-pattern و
# data-error-pattern می‌گذارد تا اعتبارسنجی مرورگر = اعتبارسنجی سرور.
# ---------------------------------------------------------------------------
PHONE_PATTERN = r"09\d{9}"
PHONE_ERROR = _("شماره موبایل معتبر نیست (مثال: 09121234567).")
POSTAL_CODE_PATTERN = r"[0-9]+"
POSTAL_CODE_ERROR = _("کد پستی باید فقط شامل رقم باشد.")


# ---------------------------------------------------------------------------
# خطاهای میدان‌ها (forms.py)
# ---------------------------------------------------------------------------
INVALID_CHOICE = _("گزینه انتخابی معتبر نیست.")
SERVICE_REQUIRED = _("ابتدا خدمت موردنظر را انتخاب کنید.")
BRAND_REQUIRED = _("نام برند را وارد کنید.")
PROBLEM_REQUIRED = _("شرح مشکل را وارد کنید.")

# پیام میدان الزامی: عمداً با متن کلاینت (wizard-form.js) یکسان است تا
# پیام سمت سرور و کلاینت یک صدا باشند.
REQUIRED = _("این بخش را کامل کنید.")

# خطاهای آپلود (validate_image_file) — متن پایه با جا‌نگهدار برای اعداد.
IMAGE_FORMAT_ERROR = _("فرمت تصویر مجاز نیست (فقط JPG، PNG یا WebP).")
IMAGE_MIME_ERROR = _("نوع فایل مجاز نیست (فقط تصویر).")
IMAGE_INVALID_ERROR = _("فایل ارسالی یک تصویر معتبر نیست.")
IMAGE_SIZE_BASE = _("حجم تصویر نباید بیشتر از {max} باشد.")
IMAGE_COUNT_BASE = _("حداکثر {max} تصویر می‌توانید ارسال کنید.")


def image_size_error(max_bytes: int):
    """«حجم تصویر نباید بیشتر از ۸ مگابایت باشد.» با فرمت فارسی."""
    return str(IMAGE_SIZE_BASE).format(max=megabytes(max_bytes))


def image_count_error(max_count: int):
    """«حداکثر ۵ تصویر می‌توانید ارسال کنید.» با ارقام فارسی."""
    return str(IMAGE_COUNT_BASE).format(max=fa_digits(max_count))


# ---------------------------------------------------------------------------
# پیام‌های framework (views.py) — عمداً یک پیام واحد برای «اطلاعات ناقص» تا
# صفحه و اعلان‌ها بسته به مسیر لحن عوض نکنند.
# ---------------------------------------------------------------------------
INCOMPLETE_REQUEST = _("اطلاعات درخواست کامل نیست؛ لطفاً مراحل را از ابتدا طی کنید.")
SUBMIT_FAILED = _("خطایی در ثبت درخواست رخ داد. لطفاً دوباره تلاش کنید.")
SUBMITTED_BEFORE = _("این درخواست قبلاً ثبت شده است.")
STEP_INVALID = _("مرحله نامعتبر است.")

# جداکننده‌ی پیام‌های چندگانه (مثلاً خطاهای متعدد آپلود) — نقطه‌ویرگول فارسی.
MESSAGE_SEPARATOR = "؛ "
